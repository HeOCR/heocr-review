// Turn design/review/icons/*.svg into src/web/icons.gen.ts: each icon's shapes as [tag, attributes] and whether it
// mirrors in Hebrew (icons.json). Run after the designer changes an icon: node scripts/gen-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const DIR = "design/review/icons";
const meta = JSON.parse(readFileSync(`${DIR}/icons.json`, "utf8"));
const SHAPES = new Set(["rect", "path", "circle", "line", "polyline", "polygon", "ellipse"]);
const ATTRS = new Set(["x", "y", "width", "height", "d", "cx", "cy", "r", "rx", "ry", "x1", "y1", "x2", "y2", "points", "class"]);

const icons = {};
for (const file of readdirSync(DIR).filter((f) => f.endsWith(".svg")).sort()) {
  const name = file.slice(0, -4);
  if (!(name in meta)) throw new Error(`${file} is not in icons.json`);
  const body = readFileSync(`${DIR}/${file}`, "utf8").replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const shapes = [];
  for (const m of body.matchAll(/<([a-z]+)\s*([^>]*?)\/?>/g)) {
    const [, tag, rest] = m;
    if (tag.startsWith("/")) continue;
    if (!SHAPES.has(tag)) throw new Error(`${file}: unexpected <${tag}>`);
    const attrs = {};
    for (const a of rest.matchAll(/([a-z0-9-]+)="([^"]*)"/g)) {
      // A filled shape (fill="currentColor" stroke="none") becomes review.css's `.ico .f`.
      if ((a[1] === "fill" && a[2] === "currentColor") || (a[1] === "stroke" && a[2] === "none")) continue;
      if (!ATTRS.has(a[1])) throw new Error(`${file}: unexpected attribute ${a[1]}="${a[2]}"`);
      attrs[a[1]] = a[2];
    }
    if (/fill="currentColor"/.test(rest)) attrs.class = "f";
    shapes.push([tag, attrs]);
  }
  if (!shapes.length) throw new Error(`${file}: no shapes`);
  icons[name] = { flip: meta[name].mirrors_in_rtl === true, shapes };
}
for (const name of Object.keys(meta)) if (!(name in icons)) throw new Error(`icons.json names ${name}, which has no SVG`);

const out = `// Generated by scripts/gen-icons.mjs from design/review/icons (HeOCR/heocr-review#51). Do not edit.
export const ICONS = ${JSON.stringify(icons, null, 1)} as const satisfies Record<string, { flip: boolean; shapes: readonly (readonly [string, Record<string, string>])[] }>;
`;
writeFileSync("src/web/icons.gen.ts", out);
console.log(`${Object.keys(icons).length} icons -> src/web/icons.gen.ts`);
